# ==============================================================================
# Operational Boundary Assurance (OBA) Safety Guardian
# ==============================================================================
class DynamicOBAGuardian:
    def __init__(self, z_max=30.0):
        self.z_max = z_max

    def verify_target_waypoint(self, candidate_waypoint):
        x_target, y_target, z_target = candidate_waypoint
        target_height = -z_target
        
        modified_z = z_target
        is_safe = True

        # Kinematic altitude ceiling check
        if target_height > self.z_max:
            is_safe = False
            modified_z = -self.z_max

        return is_safe, (x_target, y_target, modified_z)


# ==============================================================================
# Single-Axis Zigzag Navigation & Llama 3.1 Tracking Loop
# ==============================================================================
def run_zigzag_tracking_simulation():
    # --------------------------------------------------------------------------
    # Step 1: Active LLM Planning via agentic_uav/planners/llama_planner.py
    # --------------------------------------------------------------------------
    user_prompt = "Follow pedestrian_1 performing zigzag movements at 3.5m trailing distance and 3.0m altitude."
    
    print("[CarlaAir] Invoking Llama 3.1 Planner from agentic_uav/planners/llama_planner.py...")
    planner = LlamaPlanner()
    
    # Send user prompt to local Llama-3.1 instance
    parsed_plan = planner.plan_mission(user_prompt)
    print(f"[Llama 3.1 Planner Output]: {parsed_plan}")

    # Extract target parameters generated by Llama 3.1
    action = parsed_plan.get("action", "TRACK_TARGET")
    params = parsed_plan.get("parameters", {})

    FOLLOW_DISTANCE = params.get("follow_distance", 3.5)
    TARGET_HEIGHT = params.get("flight_altitude", 3.0)

    print(f"\n[Llama 3.1 Approved Mission]: Action={action} | Follow Dist={FOLLOW_DISTANCE}m | Flight Alt={TARGET_HEIGHT}m\n")

    # --------------------------------------------------------------------------
    # Step 2: Initialize CARLA Environment
    # --------------------------------------------------------------------------
    print("[CarlaAir] Connecting to CARLA server...")
    carla_client = carla.Client('localhost', 2000)
    carla_client.set_timeout(10.0)
    world = carla_client.get_world()

    # Synchronous Mode (20 FPS)
    settings = world.get_settings()
    settings.synchronous_mode = True
    settings.fixed_delta_seconds = 0.05
    world.apply_settings(settings)

    bp_lib = world.get_blueprint_library()
    ped_bps = bp_lib.filter('walker.pedestrian.*')

    spectator = world.get_spectator()
    spec_transform = spectator.get_transform()
    forward_vec = spec_transform.get_forward_vector()
    right_vec = spec_transform.get_right_vector()

    spawn_loc = spec_transform.location + forward_vec * 8.0
    spawn_loc.z += 1.0

    # Spawn Walker
    walker_bp = ped_bps[0]
    if walker_bp.has_attribute('is_invincible'):
        walker_bp.set_attribute('is_invincible', 'false')

    walker_actor = world.try_spawn_actor(walker_bp, carla.Transform(spawn_loc))
    if not walker_actor:
        print("[ERROR] Failed to spawn pedestrian actor.")
        return

    world.tick()

    # --------------------------------------------------------------------------
    # Step 3: Initialize AirSim & OBA Guardian
    # --------------------------------------------------------------------------
    print("[CarlaAir] Connecting to AirSim API...")
    airsim_client = airsim.MultirotorClient()
    airsim_client.confirmConnection()
    airsim_client.enableApiControl(True)
    airsim_client.armDisarm(True)

    guardian = DynamicOBAGuardian(z_max=30.0)

    print("[AirSim] Drone taking off...")
    airsim_client.takeoffAsync().join()

    # Establish Reference Frame Alignment
    initial_ped_pos = walker_actor.get_transform().location
    initial_drone_pos = airsim_client.getMultirotorState().kinematics_estimated.position

    # Zigzag Oscillation Parameters
    SWEEP_AMPLITUDE = 1.2  # Lateral velocity bias factor
    SWEEP_FREQUENCY = 0.08 # Speed of direction oscillation

    telemetry = {
        "ped_x": [], "ped_y": [],
        "drone_cmd_x": [], "drone_cmd_y": [],
        "drone_act_x": [], "drone_act_y": []
    }

    last_sent_cmd = (None, None, None)
    print("\n[CarlaAir] Executing OBA-Supervised Llama 3.1 Tracking Loop...\n")

    try:
        for tick in range(400):  # 20-second tracking run
            world.tick()

            # Compute combined forward + oscillating lateral vector
            lateral_bias = math.sin(tick * SWEEP_FREQUENCY) * SWEEP_AMPLITUDE
            active_dir = carla.Vector3D(
                x=forward_vec.x + right_vec.x * lateral_bias,
                y=forward_vec.y + right_vec.y * lateral_bias,
                z=0.0
            )

            # Normalize vector direction
            dir_norm = math.hypot(active_dir.x, active_dir.y)
            if dir_norm > 0:
                active_dir.x /= dir_norm
                active_dir.y /= dir_norm

            # Apply velocity control to pedestrian
            ctrl = carla.WalkerControl()
            ctrl.speed = 1.4  # Walking speed (1.4 m/s)
            ctrl.direction = active_dir
            walker_actor.apply_control(ctrl)

            # Get live pedestrian location & transform
            ped_transform = walker_actor.get_transform()
            ped_pos = ped_transform.location

            # Convert CARLA displacement to AirSim-local coordinates
            delta_x = ped_pos.x - initial_ped_pos.x
            delta_y = ped_pos.y - initial_ped_pos.y

            # Compute raw waypoint using Llama 3.1 parameters
            behind_offset_x = -(active_dir.x * FOLLOW_DISTANCE)
            behind_offset_y = -(active_dir.y * FOLLOW_DISTANCE)

            raw_target_x = initial_drone_pos.x_val + delta_x + behind_offset_x
            raw_target_y = initial_drone_pos.y_val + delta_y + behind_offset_y
            raw_target_z = -TARGET_HEIGHT

            # Verify waypoint through OBA Layer (< 50µs)
            is_safe, (cmd_x, cmd_y, cmd_z) = guardian.verify_target_waypoint(
                (raw_target_x, raw_target_y, raw_target_z)
            )

            # Dispatch movement command to AirSim on displacement threshold (> 0.20m shift)
            if last_sent_cmd[0] is None or math.dist((cmd_x, cmd_y, cmd_z), last_sent_cmd) > 0.20:
                airsim_client.moveToPositionAsync(cmd_x, cmd_y, cmd_z, velocity=3.0)
                last_sent_cmd = (cmd_x, cmd_y, cmd_z)

            # Record telemetry
            drone_actual = airsim_client.getMultirotorState().kinematics_estimated.position
            
            telemetry["ped_x"].append(initial_drone_pos.x_val + delta_x)
            telemetry["ped_y"].append(initial_drone_pos.y_val + delta_y)
            telemetry["drone_cmd_x"].append(cmd_x)
            telemetry["drone_cmd_y"].append(cmd_y)
            telemetry["drone_act_x"].append(drone_actual.x_val)
            telemetry["drone_act_y"].append(drone_actual.y_val)

            if tick % 40 == 0:
                print(f"Tick {tick:03d} | Ped Local: ({delta_x:.2f}, {delta_y:.2f}) | "
                      f"OBA Target Cmd: ({cmd_x:.2f}, {cmd_y:.2f}, {cmd_z:.2f})")

    finally:
        print("\n[Cleanup] Resetting simulation environment...")
        walker_actor.destroy()
        airsim_client.landAsync().join()
        airsim_client.enableApiControl(False)
        settings.synchronous_mode = False
        world.apply_settings(settings)
        print("[Cleanup] Simulation execution complete.")

    plot_zigzag_trajectory(telemetry)


# ==============================================================================
# Plotting Utility
# ==============================================================================
def plot_zigzag_trajectory(data):
    print("\n[CarlaAir Data] Generating trajectory comparison plot...")
    plt.figure(figsize=(12, 6))

    plt.plot(data["ped_x"], data["ped_y"], 'r--', linewidth=2, label="Pedestrian Zigzag Path (CARLA)")
    plt.plot(data["drone_cmd_x"], data["drone_cmd_y"], 'g:', linewidth=1.5, label="OBA Target Waypoints")
    plt.plot(data["drone_act_x"], data["drone_act_y"], 'b-', linewidth=2, label="Drone Actual Flight Path (AirSim)")

    plt.scatter(data["ped_x"][0], data["ped_y"][0], color='red', marker='o', s=100, label="Pedestrian Start")
    plt.scatter(data["drone_act_x"][0], data["drone_act_y"][0], color='blue', marker='^', s=100, label="Drone Start")

    plt.title("Llama 3.1 Guided Single-Axis Zigzag Tracking with OBA Guardrail", fontsize=13, fontweight='bold')
    plt.xlabel("X Position (meters - AirSim Local Frame)", fontsize=11)
    plt.ylabel("Y Position (meters - AirSim Local Frame)", fontsize=11)
    plt.grid(True, linestyle='--', alpha=0.6)
    plt.legend(loc="upper right", fontsize=10)
    plt.axis('equal')

    plt.tight_layout()
    plt.savefig("llama_zigzag_tracking_plot.png", dpi=300)
    print("[CarlaAir Data] Plot successfully saved to 'llama_zigzag_tracking_plot.png'.")
    plt.show()


if __name__ == "__main__":
    run_zigzag_tracking_simulation()
